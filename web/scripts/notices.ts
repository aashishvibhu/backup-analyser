// Regenerates THIRD_PARTY_NOTICES.md (repo root) and public/third-party-notices.txt (shipped with the app)
// from the licence files of every library bundled into the production build.
//
//   npm run notices

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

// Runtime dependencies that end up in dist/ (dev tooling is not distributed).
const BUNDLED = ['react', 'react-dom', 'scheduler', 'sql.js', 'echarts', 'zrender', 'tslib'];

const root = join(import.meta.dirname, '..');
const read = (pkg: string, file: string) => readFileSync(join(root, 'node_modules', pkg, file), 'utf8').trim();
const find = (pkg: string, names: string[]) => names.find((n) => existsSync(join(root, 'node_modules', pkg, n)));

const sections = BUNDLED.map((pkg) => {
  const meta = JSON.parse(read(pkg, 'package.json'));
  const licenceFile = find(pkg, ['LICENSE', 'LICENSE.txt', 'LICENSE.md', 'license']);
  const noticeFile = find(pkg, ['NOTICE', 'NOTICE.txt']);
  let text = licenceFile ? read(pkg, licenceFile) : `Licence: ${meta.license}`;
  // ECharts ships the full Apache-2.0 text plus subcomponent notes; keep the notes, point to the licence.
  if (pkg === 'echarts') {
    const cut = text.indexOf('Apache ECharts Subcomponents:');
    text = 'Licensed under the Apache License, Version 2.0 (full text in the LICENSE file of this repository).\n\n' + text.slice(cut);
    const d3 = find(pkg, ['licenses/LICENSE-d3']);
    if (d3) text += '\n\n--- licenses/LICENSE-d3 ---\n\n' + read(pkg, d3);
  }
  const notice = noticeFile ? `\n\nNOTICE:\n\n${read(pkg, noticeFile)}` : '';
  const home = typeof meta.repository === 'string' ? meta.repository : (meta.repository?.url ?? meta.homepage ?? '');
  return `## ${meta.name} ${meta.version} (${meta.license})\n\n${home}\n\n\`\`\`\n${text}${notice}\n\`\`\``;
});

const body = `# Third-party notices

Backup Analyser bundles the following open-source libraries in its production build.
Their licences and notices are reproduced below. Generated by \`npm run notices\`.

${sections.join('\n\n')}
`;

writeFileSync(join(root, '..', 'THIRD_PARTY_NOTICES.md'), body);
writeFileSync(join(root, 'public', 'third-party-notices.txt'), body);
console.log(`Wrote notices for ${BUNDLED.length} libraries.`);
