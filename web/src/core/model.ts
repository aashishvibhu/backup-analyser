// Canonical, source-independent model. Only `parser/` knows Realbyte table names.

export type IsoDate = string; // YYYY-MM-DD, the date the user assigned to the entry

export type TxnKind =
  | 'income'
  | 'expense'
  | 'transfer' // one row per transfer (the raw 3/4 pair is merged)
  | 'adjustIn' // balance edited upward, not counted as income (DO_TYPE 7)
  | 'adjustOut'; // balance edited downward, not counted as expense (DO_TYPE 8)

export interface Transaction {
  id: string;
  kind: TxnKind;
  date: IsoDate;
  /** Epoch ms incl. time of day. Approximate: back-dated entries keep entry time. */
  timestamp: number;
  /** Amount in the transaction currency, always positive. */
  amount: number;
  /** Amount in the main currency, always positive. */
  amountMain: number;
  currency: string;
  accountId: string;
  /** Amount in `accountId`'s currency (what moves its balance). */
  accountAmount: number;
  /** Destination account for transfers. */
  toAccountId?: string;
  /** Amount credited to `toAccountId`, in its currency. */
  toAccountAmount?: number;
  categoryId?: string;
  memo: string;
  /** Income/expense created by the app's "modify balance" flow (system category -4). */
  isBalanceCorrection: boolean;
  /** Set when the row was generated by a repeat rule. */
  recurringId?: string;
}

export type AccountKind =
  | 'cash'
  | 'bank'
  | 'creditCard'
  | 'debitCard'
  | 'deposit'
  | 'loan'
  | 'prepaid'
  | 'investment'
  | 'overdraft'
  | 'insurance'
  | 'other'
  | 'custom';

export interface AccountGroup {
  id: string;
  name: string;
  kind: AccountKind;
  order: number;
  deleted: boolean;
}

export interface Account {
  id: string;
  name: string;
  groupId: string;
  kind: AccountKind;
  currency: string;
  order: number;
  /** Raw ASSETS.ZDATA. Meaning not yet confirmed (0 = normal; 1 and 3 seen on hidden/excluded accounts). */
  statusFlag: number;
  card?: {
    statementDay: number;
    paymentDay: number;
    /** Account the card is paid from. */
    paidFromAccountId?: string;
  };
}

export interface Category {
  id: string;
  name: string;
  type: 'income' | 'expense';
  parentId?: string;
  order: number;
  deleted: boolean;
}

export interface Currency {
  id: string;
  iso: string;
  name: string;
  symbol: string;
  /** Units of main currency per 1 unit of this currency. */
  rate: number;
  isMain: boolean;
}

export interface Budget {
  id: string;
  categoryId?: string;
  isTotal: boolean;
  periodType: number;
  amount: number;
}

export interface RecurringRule {
  id: string;
  kind: TxnKind;
  repeatType: number;
  amount: number;
  accountId: string;
  toAccountId?: string;
  categoryId?: string;
  memo: string;
  nextDate?: number;
  endDate?: number;
}

export interface Tag {
  id: string;
  name: string;
}

export interface Settings {
  /** Day of month a period starts on (1–31). Clamped to the month's length. */
  monthStartDay: number;
  /** Raw week_start_day value. */
  weekStartDay: number;
  carryOver: boolean;
  /** Raw card_accounting_type value. */
  cardAccountingType: number;
  /** All raw ZETC key/values for later decoding. */
  raw: Record<string, string>;
}

export interface Dataset {
  meta: {
    sourceName: string;
    schemaVersion: number;
    parsedAt: number;
    mainCurrency: string;
    warnings: string[];
    rowCounts: Record<string, number>;
  };
  settings: Settings;
  accountGroups: AccountGroup[];
  accounts: Account[];
  categories: Category[];
  currencies: Currency[];
  transactions: Transaction[];
  budgets: Budget[];
  recurring: RecurringRule[];
  tags: Tag[];
  /** txn id → tag ids */
  txnTags: Record<string, string[]>;
}
